use crate::{
    cli::{Standard, Template},
    config::ProjectConfig,
};
use anyhow::{Context, Result, bail};
use std::{fs, path::Path};

pub fn validate_name(name: &str) -> Result<()> {
    if name.is_empty()
        || !name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
        || !name
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
    {
        bail!(
            "invalid project name '{name}': use letters, numbers, '-' or '_' and start with a letter"
        )
    }
    Ok(())
}

pub fn create_project(
    root: &Path,
    config: &ProjectConfig,
    template: &Template,
    tests: bool,
    force: bool,
) -> Result<()> {
    if root.exists() && !force && root.read_dir().is_ok_and(|mut e| e.next().is_some()) {
        bail!(
            "directory {} is not empty (use --force to continue)",
            root.display()
        );
    }
    for directory in ["src", "include"] {
        fs::create_dir_all(root.join(directory))
            .with_context(|| format!("creating {}", root.join(directory).display()))?;
    }
    let c = config.language.eq_ignore_ascii_case("c");
    let ext = if c { "c" } else { "cpp" };
    let source = if matches!(template, Template::HeaderOnly) {
        format!(
            "// {name} header-only library\n#pragma once\n\nnamespace {name} {{\ninline int version() {{ return 1; }}\n}}\n",
            name = config.name
        )
    } else if c && matches!(template, Template::Library) {
        "int forge_library(void) { return 1; }\n".to_owned()
    } else if c {
        "int main(void) { return 0; }\n".to_owned()
    } else if matches!(template, Template::Library) {
        "int forge_library() { return 1; }\n".to_owned()
    } else {
        "#include <iostream>\n\nint main() {\n    std::cout << \"Hello from Forge!\\n\";\n    return 0;\n}\n".to_owned()
    };
    let source_path = if matches!(template, Template::HeaderOnly) {
        root.join("include").join(&config.name).join("library.hpp")
    } else {
        root.join("src").join(format!("main.{ext}"))
    };
    write_if_missing(&source_path, &source)?;
    let cmake = cmake_text(config, template, tests, c, &source_path, root);
    write_if_missing(&root.join("CMakeLists.txt"), &cmake)?;
    write_if_missing(
        &root.join("README.md"),
        &format!(
            "# {}\n\nGenerated by Forge.\n\n```sh\nforge build\nforge run\n```\n",
            config.name
        ),
    )?;
    write_if_missing(
        &root.join(".gitignore"),
        "build/\ncmake-build-*/\n.vscode/\n.idea/\n",
    )?;
    if tests {
        let test_dir = root.join("tests");
        fs::create_dir_all(&test_dir)?;
        write_if_missing(
            &test_dir.join(format!("smoke.{ext}")),
            if c {
                "int main(void) { return 0; }\n"
            } else {
                "#include <cassert>\nint main() { assert(true); }\n"
            },
        )?;
    }
    config.write(root)
}

fn write_if_missing(path: &Path, content: &str) -> Result<()> {
    if !path.exists() {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(())
}

fn cmake_text(
    config: &ProjectConfig,
    template: &Template,
    tests: bool,
    c: bool,
    source: &Path,
    root: &Path,
) -> String {
    let lang = if c { "C" } else { "CXX" };
    let standard = config
        .defaults
        .standard
        .trim_start_matches('c')
        .trim_start_matches('+');
    let source = source
        .strip_prefix(root)
        .unwrap_or(source)
        .display()
        .to_string();
    let standard_language = if c { "C" } else { "CXX" };
    let mut out = format!(
        "cmake_minimum_required(VERSION {})\nproject({} VERSION 0.1.0 LANGUAGES {})\nset(CMAKE_{}_STANDARD {})\nset(CMAKE_{}_STANDARD_REQUIRED ON)\nset(CMAKE_{}_EXTENSIONS OFF)\n",
        config.cmake_minimum.as_deref().unwrap_or("3.16"),
        config.name,
        lang,
        standard_language,
        standard,
        standard_language,
        standard_language
    );
    match template {
        Template::Executable => out.push_str(&format!(
            "add_executable({} {})\ntarget_include_directories({} PRIVATE include)\n",
            config.name, source, config.name
        )),
        Template::Library => out.push_str(&format!(
            "add_library({} STATIC {})\ntarget_include_directories({} PUBLIC include)\n",
            config.name, source, config.name
        )),
        Template::HeaderOnly => out.push_str(&format!(
            "add_library({} INTERFACE)\ntarget_include_directories({} INTERFACE include)\n",
            config.name, config.name
        )),
    }
    if tests {
        out.push_str(&format!("enable_testing()\nadd_executable({}_test tests/smoke.{} )\nadd_test(NAME smoke COMMAND {}_test)\n", config.name, if c {"c"} else {"cpp"}, config.name));
    }
    out
}

pub fn standard_string(s: &Option<Standard>, language: &str) -> String {
    s.as_ref().map_or_else(
        || {
            if language == "c" {
                "c11".to_owned()
            } else {
                "c++17".to_owned()
            }
        },
        |v| format!("{v:?}").to_lowercase().replace("xx", "++"),
    )
}
